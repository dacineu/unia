//! Writes a generated corpus to a directory and reports what it converges on.
//!
//! Exists because the numbers in `docs/` have to be reproducible by whoever reads
//! them, and because "the corpus generator works" is not a claim — "here is the
//! corpus, here is what it converges on, here is how many ways each convergence
//! can be asked for" is.
//!
//! Every artifact it writes says in its own `guidance` field that it is
//! synthetic. That is not decoration: a corpus of invented artifacts measured
//! without that label is a way of being believed by accident.

use std::collections::BTreeMap;
use std::io::Write;
use std::path::PathBuf;

use unia::gather::{gather, Readiness, Sphere};
use unia::identifiers::DuUuid;

fn usage() -> &'static str {
    "usage: unia-corpus [--out DIR] [--per-profile N] [--seed N] [--quiet]\n\
     \n\
     Writes a synthetic .ure corpus and reports the denominators it converges on.\n\
     \n\
     Defaults: --out .unia/out/generated --per-profile 6 --seed 11\n"
}

struct Args {
    out: PathBuf,
    per_profile: usize,
    seed: u64,
    quiet: bool,
}

fn parse() -> Result<Args, String> {
    let mut args = Args {
        out: PathBuf::from(".unia/out/generated"),
        per_profile: 6,
        seed: 11,
        quiet: false,
    };
    let raw: Vec<String> = std::env::args().skip(1).collect();
    let mut i = 0;
    while i < raw.len() {
        match raw[i].as_str() {
            "--out" => {
                i += 1;
                args.out = raw.get(i).ok_or("--out needs a directory")?.into();
            }
            "--per-profile" => {
                i += 1;
                args.per_profile = raw
                    .get(i)
                    .ok_or("--per-profile needs a number")?
                    .parse()
                    .map_err(|_| "--per-profile needs a number")?;
            }
            "--seed" => {
                i += 1;
                args.seed = raw
                    .get(i)
                    .ok_or("--seed needs a number")?
                    .parse()
                    .map_err(|_| "--seed needs a number")?;
            }
            "--quiet" => args.quiet = true,
            "-h" | "--help" => {
                print!("{}", usage());
                std::process::exit(0);
            }
            other => return Err(format!("unknown argument {other:?}")),
        }
        i += 1;
    }
    Ok(args)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = parse().map_err(|e| {
        eprintln!("unia-corpus: {e}\n\n{}", usage());
        e
    })?;

    std::fs::create_dir_all(&args.out)?;

    let mut written = 0usize;
    let mut spheres = Vec::new();

    for (name, manifest) in unia::corpus::corpus(args.seed, args.per_profile) {
        let path = args.out.join(format!("{name}.ure"));
        let mut f = std::fs::File::create(&path)?;
        f.write_all(serde_json::to_string_pretty(&manifest)?.as_bytes())?;
        written += 1;

        // The sphere is built from the manifest as written, not from the
        // generator's in-memory copy, so what is reported is what a reader of the
        // directory would find.
        let address = DuUuid::generate(&manifest, None)?.to_string();
        let actions: Vec<String> = manifest["action_primitives"]
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x["id"].as_str().map(str::to_string))
                    .collect()
            })
            .unwrap_or_default();
        let aliases: Vec<String> = manifest["action_primitives"]
            .as_array()
            .map(|a| {
                a.iter()
                    .flat_map(|x| {
                        x["aliases"]
                            .as_array()
                            .map(|v| {
                                v.iter()
                                    .filter_map(|s| s.as_str().map(str::to_string))
                                    .collect::<Vec<_>>()
                            })
                            .unwrap_or_default()
                    })
                    .collect()
            })
            .unwrap_or_default();
        spheres.push(Sphere::new(address, actions, aliases, Readiness::new(0.5)));
    }

    if !args.quiet {
        println!("corpus written to {}", args.out.display());
    }

    // Convergence is reported rather than asserted. A denominator here means two
    // or more artifacts with *exactly* the same set of action ids, reached from
    // different content addresses — which is the shape the project's central claim
    // takes, and the reason the corpus is generated by profile.
    let gathered = gather(&spheres);
    let mut by_contributors: BTreeMap<usize, usize> = BTreeMap::new();
    for d in &gathered.denominators {
        *by_contributors.entry(d.convergence).or_default() += 1;
    }

    if !args.quiet {
        println!("  artifacts            {written}");
        println!("  denominators         {}", gathered.denominators.len());
        println!("  ties observed        {}", gathered.ties.len());
        println!();
        for (contributors, count) in &by_contributors {
            println!("  {count} denominator(s) reached by {contributors} artifacts");
        }
        for d in gathered.denominators.iter().take(12) {
            let mut names: Vec<&str> = d.capability.0.iter().map(String::as_str).collect();
            names.sort_unstable();
            println!(
                "    {:<52} contributors={} phrasings={}",
                names.join("+"),
                d.contributors.len(),
                d.aliases.len()
            );
        }
        println!();
        println!(
            "  Every manifest above is synthetic. Numbers taken on it measure the \
             machinery, not the world."
        );
    }

    Ok(())
}
